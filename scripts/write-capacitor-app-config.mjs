/**
 * Writes capacitor-www/app-config.js used by the local bootstrap shell
 * before it navigates to the hosted Next.js app.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const serverUrl = (
  process.env.CAPACITOR_SERVER_URL?.trim() ||
  "https://regi-90502049802.us-central1.run.app"
).replace(/\/$/, "");

const contents = `/* Generated by scripts/write-capacitor-app-config.mjs — do not edit */
window.REGI_CAPACITOR = ${JSON.stringify({ serverUrl }, null, 2)};
`;

writeFileSync(join(root, "capacitor-www", "app-config.js"), contents, "utf8");
console.log(`[capacitor] app-config.js → ${serverUrl}`);
